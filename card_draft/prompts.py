def build_user_prompt(product: Product) -> str:
    data = {
        "name": product.name,
        "manufacturer": product.manufacturer or "данных нет",
        "specs": product.specs,
        "description": product.description or "данных нет",
    }
    block = json.dumps(data, ensure_ascii=False, indent=2).replace("</", "<\\/")
    return f"<product>\n{block}\n</product>"


def build_fix_prompt(problems: list[str]) -> str:
    listed = "\n".join(f"- {problem}" for problem in problems)
    return (
        "В ответе найдены проблемы:\n"
        f"{listed}\n"
        "Исправь их. Значение, которого нет в <product>, удали, а не заменяй другим. "
        "Верни весь JSON-объект заново."
    )
